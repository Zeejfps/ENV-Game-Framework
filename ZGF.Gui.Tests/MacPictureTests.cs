using ZGF.Gui.Hosting;

namespace ZGF.Gui.Tests;

public class MacPictureTests
{
    // 2x1 RGBA: opaque red, then blue at half alpha.
    private static readonly byte[] TwoPixelPng =
    [
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
        0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0xF4, 0x22, 0x7F,
        0x8A, 0x00, 0x00, 0x00, 0x0E, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0xF8, 0xCF, 0xC0, 0x00,
        0x42, 0x0D, 0x00, 0x0F, 0x7A, 0x03, 0x7E, 0x77, 0xE9, 0x7F, 0x97, 0x00, 0x00, 0x00, 0x00, 0x49,
        0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
    ];

    [Fact]
    public void A_png_reads_as_its_straight_alpha_pixels()
    {
        if (!OperatingSystem.IsMacOS()) return;

        var image = MacPicture.Decode(TwoPixelPng)!;

        Assert.Equal((2, 1), (image.Width, image.Height));
        Assert.Equal(new byte[] { 0xFF, 0, 0, 0xFF, 0, 0, 0xFF, 0x80 }, image.Rgba);
    }

    [Fact]
    public void Bytes_that_are_no_picture_read_as_none()
    {
        if (!OperatingSystem.IsMacOS()) return;

        Assert.Null(MacPicture.Decode("not a picture"u8));
    }

    [Fact]
    public void Straightening_divides_color_by_alpha_and_leaves_clear_and_opaque_pixels()
    {
        byte[] rgba = [0x40, 0x20, 0x80, 0x80, 1, 2, 3, 0, 9, 8, 7, 0xFF];

        MacPicture.Straighten(rgba);

        Assert.Equal(new byte[] { 0x80, 0x40, 0xFF, 0x80, 1, 2, 3, 0, 9, 8, 7, 0xFF }, rgba);
    }
}
